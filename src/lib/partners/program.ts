/** The next payout date (the 15th), as YYYY-MM-DD. */
export function nextPayoutDate(now: number) {
  const d = new Date(now);
  const day = PROGRAM.payoutDay;
  const target = d.getUTCDate() < day ? new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), day)) : new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + 1, day));
  return target.toISOString().slice(0, 10);
}

